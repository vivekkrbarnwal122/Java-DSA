public class datatypes {
     public static void main (String[] args){
//integer-->byte,short,int,long
byte b=7;
short s=20;
int i=20000;
long l=100000;
System.out.println("integer values-->" + b + "," + s +","+ i + ", "+l);

//real no.-->float, double
float f=23.98f;
double d=5364.878;
System.out.println("real no.-->" + f +","+d );

//character:'y'-->integer-->binary-->store
char c='y';
System.out.println("character-->"+c);

//boolean 
boolean B=true;
System.out.println("boolean values-->"+B);
     }
 }
