public class specialRepre {
    public static void main(String[] args) {
        //here we represent interger values using binary(2),octal(8) and hexadecimal(16)
        //for binary representation we use prefix 0b or 0B
        //for octal representation we use prefix 0
        //for hexadecimal representation we use prefix 0x or 0X
        int i =0b1010; //binary representation of 10
        int j=012; //octal representation of 10
        int k=0xA; //hexadecimal representation of 10
        System.out.println(i + ", " + j + ", "+ k);
    }
}
